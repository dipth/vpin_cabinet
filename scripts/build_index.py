"""Write build/index.html linking every rendered harness sheet.

Stdlib only, so it runs on the plain mise-managed Python.
"""

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"


def section(text: str, div_id: str) -> str:
    match = re.search(rf'<div id="{div_id}">\s*(.*?)\s*</div>', text, re.S)
    return match.group(1).strip() if match else ""


def main() -> None:
    cards = []
    for page in sorted(BUILD.glob("[0-9]*.html")):
        text = page.read_text(encoding="utf-8")
        title = re.search(r"<title>(.*?)</title>", text, re.S).group(1).strip()
        stem = page.stem
        cards.append(
            f"""
    <article>
      <h2><a href="{stem}.html">{html.escape(title)}</a></h2>
      <p>{section(text, "description")}</p>
      <details><summary>Notes</summary><p>{section(text, "notes")}</p></details>
      <a class="thumb" href="{stem}.svg"><img src="{stem}.svg" alt="{html.escape(title)} diagram" loading="lazy"></a>
      <nav>
        <a href="{stem}.html">Diagram + BOM</a>
        <a href="{stem}.svg">SVG</a>
        <a href="{stem}.png">PNG</a>
        <a href="{stem}.bom.tsv">BOM (TSV)</a>
      </nav>
    </article>"""
        )

    (BUILD / "index.html").write_text(
        f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Virtual Pinball Wiring Plan</title>
  <style>
    body {{ font-family: -apple-system, Segoe UI, Arial, sans-serif; margin: 0 auto; max-width: 1100px; padding: 24px 16px; color: #222; background: #fafafa; }}
    h1 {{ margin-bottom: 4px; }}
    article {{ background: #fff; border: 1px solid #ddd; border-radius: 8px; padding: 16px 20px; margin: 16px 0; }}
    h2 {{ margin: 0 0 8px; font-size: 1.15rem; }}
    .thumb img {{ width: 100%; max-height: 260px; object-fit: contain; border: 1px solid #eee; background: #fff; }}
    nav a {{ margin-right: 14px; }}
    details {{ margin: 8px 0; font-size: .92rem; }}
    a {{ color: #0b57d0; }}
  </style>
</head>
<body>
  <h1>Virtual Pinball Wiring Plan</h1>
  <p>Generated by WireViz from <code>harness/*.yml</code>. Rebuild with <code>mise run build</code>.</p>
  <p><strong><a href="bom.html">Build BOM with shop links →</a></strong></p>
  {"".join(cards)}
</body>
</html>
""",
        encoding="utf-8",
    )
    print(f"Wrote {BUILD / 'index.html'} ({len(cards)} sheets)")


if __name__ == "__main__":
    main()
